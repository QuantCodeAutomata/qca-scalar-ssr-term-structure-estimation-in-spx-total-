# ---------------------------------------------------------------------------
# Test 1: local_cubic_jets accuracy
# ---------------------------------------------------------------------------


def test_local_cubic_jets_accuracy():
    """
    Given a smile generated by a known cubic polynomial, local_cubic_jets
    should recover b0 = w(k0) and b1 = w'(k0) to at least 6 decimal places
    (exact recovery since the DGP is cubic and 11 nodes > 4 parameters).
    """
    # Known polynomial: w(k) = 0.05 - 0.12*k + 0.30*k^2 - 0.08*k^3
    a0, a1, a2_raw, a3_raw = 0.05, -0.12, 0.30, -0.08
    k_grid = K_GRID.copy()
    w_grid = a0 + a1 * k_grid + a2_raw * k_grid ** 2 + a3_raw * k_grid ** 3

    k0 = np.log(0.975)  # one of the standard centers
    b0, b1, b2, r2 = local_cubic_jets(k_grid, w_grid, k0)

    # Expected values via the polynomial
    expected_b0 = a0 + a1 * k0 + a2_raw * k0 ** 2 + a3_raw * k0 ** 3
    expected_b1 = a1 + 2 * a2_raw * k0 + 3 * a3_raw * k0 ** 2

    assert abs(b0 - expected_b0) < 1e-10, f"b0 error: {b0 - expected_b0:.2e}"
    assert abs(b1 - expected_b1) < 1e-10, f"b1 error: {b1 - expected_b1:.2e}"
    assert 0.99 < r2 <= 1.0 + 1e-9, f"r2 should be ~1 for noise-free cubic: {r2}"


# ---------------------------------------------------------------------------
# Test 2: estimate_local_velocity returns valid keys
# ---------------------------------------------------------------------------


def test_estimate_local_velocity_returns_valid_keys(small_panel):
    """
    estimate_local_velocity must return a dict containing exactly the keys
    {v0, se_hc3, t_stat, p_val} with finite numeric values.
    """
    k0 = K0_CENTERS[3]  # ATM center (k0 = log(0.975))
    df_node = build_local_velocity_data(small_panel, "3M", k0)

    assert len(df_node) >= 3, "Need at least 3 observations for OLS"

    result = estimate_local_velocity(df_node)

    expected_keys = {"v0", "se_hc3", "t_stat", "p_val"}
    assert set(result.keys()) == expected_keys, f"Unexpected keys: {set(result.keys())}"

    for key in expected_keys:
        val = result[key]
        assert np.isfinite(val), f"Key '{key}' is not finite: {val}"
    assert result["se_hc3"] >= 0.0, f"Standard error must be non-negative: {result['se_hc3']}"
    assert 0.0 <= result["p_val"] <= 1.0, f"p-value out of [0,1]: {result['p_val']}"


# ---------------------------------------------------------------------------
# Test 3: smooth_trend_wald_test shape and key presence
# ---------------------------------------------------------------------------


def test_smooth_trend_wald_test_shape():
    """
    smooth_trend_wald_test must return a dict with keys {c1, c2, wald_stat,
    p_value}.  With a non-trivial Sigma the wald_stat should be finite and
    positive, and p_value in [0, 1].
    """
    rng = np.random.default_rng(0)
    n = len(K0_CENTERS)  # 7
    v_hat = rng.uniform(0.8, 1.6, size=n)
    Sigma = np.eye(n) * 0.01  # diagonal bootstrap covariance

    result = smooth_trend_wald_test(v_hat, K0_CENTERS, Sigma)

    expected_keys = {"c1", "c2", "wald_stat", "p_value"}
    assert set(result.keys()) == expected_keys, f"Unexpected keys: {set(result.keys())}"

    assert np.isfinite(result["wald_stat"]), "wald_stat must be finite"
    assert result["wald_stat"] >= 0.0, "wald_stat must be non-negative"
    assert 0.0 <= result["p_value"] <= 1.0, f"p_value out of [0,1]: {result['p_value']}"
    assert np.isfinite(result["c1"]) and np.isfinite(result["c2"])


# ---------------------------------------------------------------------------
# Test 4: velocity estimates are not all identical (strike-dependence)
# ---------------------------------------------------------------------------


def test_velocity_not_constant_with_known_data(small_panel):
    """
    On synthetic SPX data the local velocity should vary across k0 centers
    (the DGP has non-trivial skew and convexity).  The range of v_hat across
    the seven centers must be at least 0.01.
    """
    tenor = "3M"
    v_estimates = []
    for k0 in K0_CENTERS:
        df_node = build_local_velocity_data(small_panel, tenor, k0)
        if len(df_node) < 3:
            continue
        est = estimate_local_velocity(df_node)
        v_estimates.append(est["v0"])

    assert len(v_estimates) >= 4, "Need at least 4 valid nodes to test spread"

    v_arr = np.array(v_estimates)
    spread = float(v_arr.max() - v_arr.min())
    assert spread > 0.01, (
        f"v0 range across k0 centers is only {spread:.5f}; "
        "expected strike-dependent velocity profile"
    )
